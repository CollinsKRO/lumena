import { Command } from 'commander';
import inquirer from 'inquirer';
import { Keypair } from '@stellar/stellar-sdk';
import * as fs from 'fs';
import * as path from 'path';

export interface InitOptions {
  json?: boolean;
  network?: string;
  serverUrl?: string;
  output?: string;
  skipFunding?: boolean;
}

export interface InitResult {
  success: boolean;
  envPath?: string;
  sponsorPublicKey?: string;
  cosignerPublicKey?: string;
  network?: string;
  serverUrl?: string;
  funded?: boolean;
  error?: string;
}

const FRIENDBOT_URL = 'https://friendbot.stellar.org';

const DEFAULT_SERVER_URLS: Record<string, string> = {
  testnet: 'https://horizon-testnet.stellar.org',
  mainnet: 'https://horizon.stellar.org',
  futurenet: 'https://horizon-futurenet.stellar.org',
};

/**
 * Funds a Stellar account on Testnet using Friendbot.
 */
export async function fundWithFriendbot(publicKey: string): Promise<boolean> {
  const url = `${FRIENDBOT_URL}?addr=${encodeURIComponent(publicKey)}`;
  const response = await fetch(url, { method: 'GET' });
  if (!response.ok) {
    const body = await response.text().catch(() => '');
    throw new Error(
      `Friendbot funding failed for ${publicKey} (status ${response.status}): ${body}`,
    );
  }
  return true;
}

/**
 * Builds the contents of the .env file from the collected configuration.
 */
export function buildEnvContent(config: {
  network: string;
  serverUrl: string;
  sponsorPublicKey: string;
  sponsorSecretKey: string;
  cosignerPublicKey: string;
  cosignerSecretKey: string;
}): string {
  return [
    '# Lumen environment configuration',
    '# Generated by `lumen init`',
    '',
    `LUMEN_NETWORK=${config.network}`,
    `LUMEN_SERVER_URL=${config.serverUrl}`,
    '',
    `SPONSOR_PUBLIC_KEY=${config.sponsorPublicKey}`,
    `SPONSOR_SECRET_KEY=${config.sponsorSecretKey}`,
    '',
    `COSIGNER_PUBLIC_KEY=${config.cosignerPublicKey}`,
    `COSIGNER_SECRET_KEY=${config.cosignerSecretKey}`,
    '',
  ].join('\n');
}

/**
 * Writes the .env file to disk, creating parent directories if needed.
 */
export function writeEnvFile(envPath: string, content: string): void {
  const dir = path.dirname(envPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(envPath, content, { encoding: 'utf8', mode: 0o600 });
}

/**
 * Runs the interactive onboarding wizard.
 */
export async function runInit(options: InitOptions = {}): Promise<InitResult> {
  const json = Boolean(options.json);

  try {
    let network = options.network;
    let serverUrl = options.serverUrl;
    let output = options.output ?? path.resolve(process.cwd(), '.env');
    let skipFunding = Boolean(options.skipFunding);

    // Interactive prompts when values are not supplied via flags.
    if (!network) {
      const answer = await inquirer.prompt<{ network: string }>([
        {
          type: 'list',
          name: 'network',
          message: 'Which Stellar network would you like to use?',
          choices: [
            { name: 'Testnet (recommended for development)', value: 'testnet' },
            { name: 'Futurenet', value: 'futurenet' },
            { name: 'Mainnet (production)', value: 'mainnet' },
          ],
          default: 'testnet',
        },
      ]);
      network = answer.network;
    }

    if (!serverUrl) {
      const defaultUrl = DEFAULT_SERVER_URLS[network] ?? DEFAULT_SERVER_URLS.testnet;
      const answer = await inquirer.prompt<{ serverUrl: string }>([
        {
          type: 'input',
          name: 'serverUrl',
          message: 'Horizon server URL:',
          default: defaultUrl,
        },
      ]);
      serverUrl = answer.serverUrl;
    }

    if (!options.output) {
      const answer = await inquirer.prompt<{ output: string }>([
        {
          type: 'input',
          name: 'output',
          message: 'Where should the .env file be written?',
          default: output,
        },
      ]);
      output = answer.output;
    }

    if (network === 'testnet' && !options.skipFunding) {
      const answer = await inquirer.prompt<{ fund: boolean }>([
        {
          type: 'confirm',
          name: 'fund',
          message: 'Fund the generated accounts on Testnet via Friendbot?',
          default: true,
        },
      ]);
      skipFunding = !answer.fund;
    }

    // Generate keypairs for sponsor and cosigner.
    const sponsor = Keypair.random();
    const cosigner = Keypair.random();

    const sponsorPublicKey = sponsor.publicKey();
    const sponsorSecretKey = sponsor.secret();
    const cosignerPublicKey = cosigner.publicKey();
    const cosignerSecretKey = cosigner.secret();

    let funded = false;
    if (network === 'testnet' && !skipFunding) {
      await fundWithFriendbot(sponsorPublicKey);
      await fundWithFriendbot(cosignerPublicKey);
      funded = true;
    }

    const envContent = buildEnvContent({
      network,
      serverUrl,
      sponsorPublicKey,
      sponsorSecretKey,
      cosignerPublicKey,
      cosignerSecretKey,
    });

    writeEnvFile(output, envContent);

    const result: InitResult = {
      success: true,
      envPath: output,
      sponsorPublicKey,
      cosignerPublicKey,
      network,
      serverUrl,
      funded,
    };

    if (json) {
      process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    } else {
      process.stdout.write('\n✅ Lumen initialization complete!\n\n');
      process.stdout.write(`  Network:            ${network}\n`);
      process.stdout.write(`  Server URL:         ${serverUrl}\n`);
      process.stdout.write(`  Sponsor public key: ${sponsorPublicKey}\n`);
      process.stdout.write(`  Cosigner public key:${cosignerPublicKey}\n`);
      process.stdout.write(`  .env written to:    ${output}\n`);
      if (funded) {
        process.stdout.write('\n  Both accounts were funded on Testnet via Friendbot.\n');
      } else if (network === 'testnet') {
        process.stdout.write('\n  Skipped Friendbot funding.\n');
      }
      process.stdout.write('\n');
    }

    return result;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    const result: InitResult = { success: false, error: message };

    if (json) {
      process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    } else {
      process.stderr.write(`\n❌ Initialization failed: ${message}\n\n`);
    }

    return result;
  }
}

/**
 * Registers the `lumen init` command.
 */
export function registerInitCommand(program: Command): Command {
  return program
    .command('init')
    .description('Interactively set up a Lumen environment and generate a .env file')
    .option('--network <network>', 'Stellar network (testnet, futurenet, mainnet)')
    .option('--server-url <url>', 'Horizon server URL')
    .option('--output <path>', 'Path to write the .env file')
    .option('--skip-funding', 'Skip funding accounts via Friendbot')
    .option('--json', 'Output the result as JSON')
    .action(async (opts: InitOptions) => {
      const result = await runInit(opts);
      if (!result.success) {
        process.exitCode = 1;
      }
    });
}

export default registerInitCommand;